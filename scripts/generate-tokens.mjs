#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'packages/tokens/tokens.json');
const outputDir = 'packages/tokens/generated';
const flutterOutputPath = 'packages/theme-flutter/lib/src/generated/tokens.dart';
const categories = ['color', 'font', 'radius', 'shadow', 'motion'];
const checkOnly = process.argv.includes('--check');

function fail(message) {
  console.error(`token generation: ${message}`);
  process.exitCode = 1;
}

function readTokens() {
  const source = JSON.parse(readFileSync(sourcePath, 'utf8'));
  if (!source || typeof source !== 'object' || Array.isArray(source)) {
    throw new Error('tokens.json must contain an object');
  }

  const unexpected = Object.keys(source).filter((key) => key !== '$comment' && !categories.includes(key));
  if (unexpected.length > 0) {
    throw new Error(`unsupported token categories: ${unexpected.join(', ')}`);
  }

  const groups = {};
  for (const category of categories) {
    const group = source[category];
    if (!group || typeof group !== 'object' || Array.isArray(group) || Object.keys(group).length === 0) {
      throw new Error(`category ${category} must be a non-empty object`);
    }

    groups[category] = {};
    for (const [name, token] of Object.entries(group)) {
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
        throw new Error(`invalid token name ${category}.${name}`);
      }
      if (!token || typeof token !== 'object' || typeof token.value !== 'string' || token.value.length === 0) {
        throw new Error(`token ${category}.${name} must have a non-empty string value`);
      }
      if (category === 'color' && !/^#[0-9a-fA-F]{6}$/.test(token.value)) {
        throw new Error(`color ${name} must use a six-digit hex value`);
      }
      if (token.note !== undefined && typeof token.note !== 'string') {
        throw new Error(`note for ${category}.${name} must be a string`);
      }
      groups[category][name] = token.value;
    }
  }
  return groups;
}

function cssOutput(groups) {
  const lines = [':root {'];
  for (const category of categories) {
    for (const [name, value] of Object.entries(groups[category])) {
      lines.push(`  --calango-${category}-${name}: ${value};`);
    }
  }
  lines.push('}', '');
  return lines.join('\n');
}

function typescriptOutput(groups) {
  return `// Generated by scripts/generate-tokens.mjs. Do not edit.\nexport const designTokens = ${JSON.stringify(groups, null, 2)} as const;\n`;
}

function dartOutput(groups) {
  const lines = ['// Generated by scripts/generate-tokens.mjs. Do not edit.', 'abstract final class CalangoTokens {'];
  for (const category of categories) {
    lines.push(`  static const Map<String, String> ${category} = <String, String>{`);
    for (const [name, value] of Object.entries(groups[category])) {
      lines.push(`    ${JSON.stringify(name)}: ${JSON.stringify(value)},`);
    }
    lines.push('  };');
  }
  lines.push('}', '');
  return lines.join('\n');
}

function dartIdentifier(name) {
  return name.replace(/-([a-z0-9])/g, (_, letter) => letter.toUpperCase());
}

function dartNumber(value) {
  const number = Number(value);
  if (!Number.isFinite(number)) throw new Error(`invalid number ${value}`);
  return Number.isInteger(number) ? `${number}.0` : String(number);
}

function argbHex(red, green, blue, alpha) {
  const channels = [Math.round(alpha * 255), red, green, blue];
  if (channels.some((channel) => !Number.isInteger(channel) || channel < 0 || channel > 255)) {
    throw new Error('color channel out of range');
  }
  return `0x${channels.map((channel) => channel.toString(16).padStart(2, '0').toUpperCase()).join('')}`;
}

function flutterColor(value) {
  return `Color(${argbHex(...[1, 3, 5].map((start) => Number.parseInt(value.slice(start, start + 2), 16)), 1)})`;
}

function pixels(value, where) {
  const match = /^(-?\d*\.?\d+)(px)?$/.exec(value);
  if (!match || (match[2] === undefined && Number(match[1]) !== 0)) throw new Error(`${where}: expected a px length`);
  return dartNumber(match[1]);
}

// CSS box-shadow -> BoxShadow. Flutter has no inset shadows, so inset layers are left out.
function flutterShadows(name, value) {
  const layers = value.split(/,(?![^(]*\))/).map((layer) => layer.trim());
  const shadows = [];
  let insetLayers = 0;
  for (const layer of layers) {
    const color = /rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d*\.?\d+)\s*\)/.exec(layer);
    if (!color) throw new Error(`shadow ${name} must use rgba() colors`);
    const parts = layer.replace(color[0], '').trim().split(/\s+/);
    if (parts[0] === 'inset') {
      insetLayers += 1;
      continue;
    }
    if (parts.length < 2 || parts.length > 4) throw new Error(`shadow ${name} has an unsupported layer: ${layer}`);
    const [x, y, blur, spread] = [0, 1, 2, 3].map((index) => pixels(parts[index] ?? '0', `shadow ${name}`));
    const argb = argbHex(Number(color[1]), Number(color[2]), Number(color[3]), Number(color[4]));
    shadows.push(
      `BoxShadow(color: Color(${argb}), offset: Offset(${x}, ${y}), blurRadius: ${blur}, spreadRadius: ${spread})`,
    );
  }
  return { shadows, insetLayers };
}

function flutterOutput(groups) {
  const lines = [
    '// Generated by scripts/generate-tokens.mjs from packages/tokens/tokens.json. Do not edit.',
    '// dart format off',
    '',
    "import 'package:flutter/animation.dart';",
    "import 'package:flutter/painting.dart';",
    '',
    '/// Brand colors.',
    'abstract final class CalangoColors {',
  ];
  for (const [name, value] of Object.entries(groups.color)) {
    lines.push(`  static const Color ${dartIdentifier(name)} = ${flutterColor(value)};`);
  }
  lines.push('}', '', '/// Font families. The app bundles the font files.', 'abstract final class CalangoFonts {');
  for (const [name, value] of Object.entries(groups.font)) {
    lines.push(`  static const String ${dartIdentifier(name)} = '${value.replace(/[\\'$]/g, '\\$&')}';`);
  }
  lines.push(
    '}',
    '',
    '/// Corner radii in logical pixels. Percentages become a `Fraction` of the shortest side.',
    'abstract final class CalangoRadii {',
  );
  for (const [name, value] of Object.entries(groups.radius)) {
    const percent = /^(\d*\.?\d+)%$/.exec(value);
    if (percent) {
      lines.push(`  static const double ${dartIdentifier(name)}Fraction = ${dartNumber(Number(percent[1]) / 100)};`);
    } else {
      lines.push(`  static const double ${dartIdentifier(name)} = ${pixels(value, `radius ${name}`)};`);
    }
  }
  lines.push('}', '', '/// Elevation shadows.', 'abstract final class CalangoShadows {');
  for (const [name, value] of Object.entries(groups.shadow)) {
    const { shadows, insetLayers } = flutterShadows(name, value);
    if (insetLayers > 0) lines.push(`  /// ${insetLayers} inset layer(s) of the CSS token have no Flutter equivalent.`);
    lines.push(`  static const List<BoxShadow> ${dartIdentifier(name)} = <BoxShadow>[`);
    for (const shadow of shadows) lines.push(`    ${shadow},`);
    lines.push('  ];');
  }
  lines.push('}', '', '/// Animation curves and durations.', 'abstract final class CalangoMotion {');
  for (const [name, value] of Object.entries(groups.motion)) {
    const bezier = /^cubic-bezier\(([^)]+)\)$/.exec(value);
    const duration = /^(\d+)ms$/.exec(value);
    if (bezier) {
      const points = bezier[1].split(',').map((point) => dartNumber(point.trim()));
      if (points.length !== 4) throw new Error(`motion ${name} needs four control points`);
      lines.push(`  static const Cubic ${dartIdentifier(name)} = Cubic(${points.join(', ')});`);
    } else if (duration) {
      lines.push(`  static const Duration ${dartIdentifier(name)} = Duration(milliseconds: ${duration[1]});`);
    } else {
      throw new Error(`motion ${name} must be a cubic-bezier() or a duration in ms`);
    }
  }
  lines.push('}', '');
  return lines.join('\n');
}

try {
  const groups = readTokens();
  const outputs = new Map([
    [`${outputDir}/tokens.css`, cssOutput(groups)],
    [`${outputDir}/tokens.ts`, typescriptOutput(groups)],
    [`${outputDir}/tokens.dart`, dartOutput(groups)],
    [flutterOutputPath, flutterOutput(groups)],
  ]);

  if (checkOnly) {
    const stale = [];
    for (const [file, expected] of outputs) {
      const filePath = path.join(root, file);
      let actual;
      try {
        actual = readFileSync(filePath, 'utf8');
      } catch {
        stale.push(file);
        continue;
      }
      if (actual !== expected) stale.push(file);
    }
    if (stale.length > 0) {
      fail(`generated files are missing or stale: ${stale.join(', ')}; run node scripts/generate-tokens.mjs`);
    } else {
      console.log('design tokens are valid and generated files are up to date');
    }
  } else {
    for (const [file, contents] of outputs) {
      mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
      writeFileSync(path.join(root, file), contents);
    }
    console.log(`generated ${outputs.size} design token files`);
  }
} catch (error) {
  fail(error instanceof Error ? error.message : String(error));
}
