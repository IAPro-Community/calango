#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'packages/tokens/tokens.json');
const outputDir = path.join(root, 'packages/tokens/generated');
const categories = ['color', 'font', 'radius', 'shadow', 'motion'];
const checkOnly = process.argv.includes('--check');

function fail(message) {
  console.error(`token generation: ${message}`);
  process.exitCode = 1;
}

function readTokens() {
  const source = JSON.parse(readFileSync(sourcePath, 'utf8'));
  if (!source || typeof source !== 'object' || Array.isArray(source)) {
    throw new Error('tokens.json must contain an object');
  }

  const unexpected = Object.keys(source).filter(
    (key) => key !== '$comment' && !categories.includes(key),
  );
  if (unexpected.length > 0) {
    throw new Error(`unsupported token categories: ${unexpected.join(', ')}`);
  }

  const groups = {};
  for (const category of categories) {
    const group = source[category];
    if (!group || typeof group !== 'object' || Array.isArray(group) || Object.keys(group).length === 0) {
      throw new Error(`category ${category} must be a non-empty object`);
    }

    groups[category] = {};
    for (const [name, token] of Object.entries(group)) {
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
        throw new Error(`invalid token name ${category}.${name}`);
      }
      if (!token || typeof token !== 'object' || typeof token.value !== 'string' || token.value.length === 0) {
        throw new Error(`token ${category}.${name} must have a non-empty string value`);
      }
      if (category === 'color' && !/^#[0-9a-fA-F]{6}$/.test(token.value)) {
        throw new Error(`color ${name} must use a six-digit hex value`);
      }
      if (token.note !== undefined && typeof token.note !== 'string') {
        throw new Error(`note for ${category}.${name} must be a string`);
      }
      groups[category][name] = token.value;
    }
  }
  return groups;
}

function cssOutput(groups) {
  const lines = [':root {'];
  for (const category of categories) {
    for (const [name, value] of Object.entries(groups[category])) {
      lines.push(`  --calango-${category}-${name}: ${value};`);
    }
  }
  lines.push('}', '');
  return lines.join('\n');
}

function typescriptOutput(groups) {
  return `// Generated by scripts/generate-tokens.mjs. Do not edit.\nexport const designTokens = ${JSON.stringify(groups, null, 2)} as const;\n`;
}

function dartOutput(groups) {
  const lines = [
    '// Generated by scripts/generate-tokens.mjs. Do not edit.',
    'abstract final class CalangoTokens {',
  ];
  for (const category of categories) {
    lines.push(`  static const Map<String, String> ${category} = <String, String>{`);
    for (const [name, value] of Object.entries(groups[category])) {
      lines.push(`    ${JSON.stringify(name)}: ${JSON.stringify(value)},`);
    }
    lines.push('  };');
  }
  lines.push('}', '');
  return lines.join('\n');
}

try {
  const groups = readTokens();
  const outputs = new Map([
    ['tokens.css', cssOutput(groups)],
    ['tokens.ts', typescriptOutput(groups)],
    ['tokens.dart', dartOutput(groups)],
  ]);

  if (checkOnly) {
    const stale = [];
    for (const [file, expected] of outputs) {
      const filePath = path.join(outputDir, file);
      let actual;
      try {
        actual = readFileSync(filePath, 'utf8');
      } catch {
        stale.push(file);
        continue;
      }
      if (actual !== expected) stale.push(file);
    }
    if (stale.length > 0) {
      fail(`generated files are missing or stale: ${stale.join(', ')}; run node scripts/generate-tokens.mjs`);
    } else {
      console.log('design tokens are valid and generated files are up to date');
    }
  } else {
    mkdirSync(outputDir, { recursive: true });
    for (const [file, contents] of outputs) {
      writeFileSync(path.join(outputDir, file), contents);
    }
    console.log(`generated ${outputs.size} design token files`);
  }
} catch (error) {
  fail(error instanceof Error ? error.message : String(error));
}
