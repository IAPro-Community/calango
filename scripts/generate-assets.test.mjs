import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const categories = ['color', 'font', 'radius', 'shadow', 'motion'];
const locales = [
  { source: 'pt-BR', arb: 'pt_BR' },
  { source: 'en', arb: 'en' },
  { source: 'es', arb: 'es' },
];

function readJSON(relativePath) {
  return JSON.parse(readFileSync(path.join(root, relativePath), 'utf8'));
}

function generatedJSON(relativePath, prefix, suffix) {
  const contents = readFileSync(path.join(root, relativePath), 'utf8');
  assert.ok(contents.startsWith(prefix), `${relativePath} has the generated header`);
  assert.ok(contents.endsWith(suffix), `${relativePath} has the expected generated footer`);
  return JSON.parse(contents.slice(prefix.length, -suffix.length));
}

test('generated token targets preserve every source value', () => {
  const source = readJSON('packages/tokens/tokens.json');
  const expected = Object.fromEntries(categories.map((category) => [
    category,
    Object.fromEntries(Object.entries(source[category]).map(([name, token]) => [name, token.value])),
  ]));

  assert.deepEqual(
    generatedJSON(
      'packages/tokens/generated/tokens.ts',
      '// Generated by scripts/generate-tokens.mjs. Do not edit.\nexport const designTokens = ',
      ' as const;\n',
    ),
    expected,
  );

  const css = readFileSync(path.join(root, 'packages/tokens/generated/tokens.css'), 'utf8');
  const cssDeclarations = [...css.matchAll(/^  (--calango-[^\n]+);$/gm)].map((match) => match[1]);
  const expectedCSS = categories.flatMap((category) => Object.entries(expected[category])
    .map(([name, value]) => `--calango-${category}-${name}: ${value}`));
  assert.equal(cssDeclarations.length, expectedCSS.length);
  assert.deepEqual(new Set(cssDeclarations), new Set(expectedCSS));

  const dart = readFileSync(path.join(root, 'packages/tokens/generated/tokens.dart'), 'utf8');
  const dartMaps = new Map([...dart.matchAll(
    /^  static const Map<String, String> ([a-z]+) = <String, String>\{\n([\s\S]*?)^  \};/gm,
  )].map((match) => {
    const values = Object.fromEntries([...match[2].matchAll(
      /^    ("(?:[^"\\]|\\.)*"): ("(?:[^"\\]|\\.)*"),$/gm,
    )].map((entry) => [JSON.parse(entry[1]), JSON.parse(entry[2])]));
    return [match[1], values];
  }));
  assert.deepEqual(Object.fromEntries(dartMaps), expected);
});

test('generated translation targets preserve all locales, keys, and values', () => {
  const source = readJSON('packages/i18n/messages.json');
  const expected = Object.fromEntries(locales.map((locale) => [locale.source, source[locale.source]]));
  const generated = generatedJSON(
    'packages/i18n/generated/messages.ts',
    '// Generated by scripts/generate-i18n.mjs. Do not edit.\nexport const messages = ',
    ' as const;\n\nexport type Locale = keyof typeof messages;\nexport type MessageKey = keyof typeof messages["pt-BR"];\n',
  );
  assert.deepEqual(generated, expected);

  for (const locale of locales) {
    assert.deepEqual(
      readJSON(`packages/i18n/generated/arb/app_${locale.arb}.arb`),
      { '@@locale': locale.arb, ...source[locale.source] },
    );
  }
});
