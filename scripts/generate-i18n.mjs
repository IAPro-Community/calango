#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'packages/i18n/messages.json');
const outputDir = path.join(root, 'packages/i18n/generated');
const locales = [
  { source: 'pt-BR', arb: 'pt_BR' },
  { source: 'en', arb: 'en' },
  { source: 'es', arb: 'es' },
];
const keyPattern = /^[a-z][A-Za-z0-9]*$/;

function isRecord(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function readCatalog() {
  const source = JSON.parse(readFileSync(sourcePath, 'utf8'));
  if (!isRecord(source)) {
    throw new Error('messages.json must contain an object');
  }

  const unexpected = Object.keys(source).filter(
    (key) => key !== '$comment' && !locales.some((locale) => locale.source === key),
  );
  if (unexpected.length > 0) {
    throw new Error(`unsupported locales: ${unexpected.join(', ')}`);
  }

  for (const locale of locales) {
    if (!Object.hasOwn(source, locale.source)) {
      throw new Error(`missing locale ${locale.source}`);
    }
  }

  let referenceKeys;
  const catalog = {};
  for (const locale of locales) {
    const messages = source[locale.source];
    if (!isRecord(messages) || Object.keys(messages).length === 0) {
      throw new Error(`locale ${locale.source} must contain messages`);
    }

    const keys = Object.keys(messages);
    for (const key of keys) {
      if (!keyPattern.test(key)) {
        throw new Error(`invalid message key ${locale.source}.${key}`);
      }
      if (typeof messages[key] !== 'string' || messages[key].trim().length === 0) {
        throw new Error(`message ${locale.source}.${key} must be a non-empty string`);
      }
    }

    if (referenceKeys === undefined) {
      referenceKeys = new Set(keys);
    } else {
      const currentKeys = new Set(keys);
      const missing = [...referenceKeys].filter((key) => !currentKeys.has(key));
      const extra = keys.filter((key) => !referenceKeys.has(key));
      if (missing.length > 0 || extra.length > 0) {
        const details = [
          missing.length > 0 ? `missing: ${missing.join(', ')}` : '',
          extra.length > 0 ? `unexpected: ${extra.join(', ')}` : '',
        ].filter(Boolean).join('; ');
        throw new Error(`locale ${locale.source} has a different key set (${details})`);
      }
    }

    catalog[locale.source] = messages;
  }
  return catalog;
}

function typescriptOutput(catalog) {
  return [
    '// Generated by scripts/generate-i18n.mjs. Do not edit.',
    `export const messages = ${JSON.stringify(catalog, null, 2)} as const;`,
    '',
    'export type Locale = keyof typeof messages;',
    'export type MessageKey = keyof typeof messages["pt-BR"];',
    '',
  ].join('\n');
}

function arbOutput(locale, messages) {
  return `${JSON.stringify({ '@@locale': locale.arb, ...messages }, null, 2)}\n`;
}

try {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== '--check')) {
    throw new Error('usage: node scripts/generate-i18n.mjs [--check]');
  }

  const catalog = readCatalog();
  const outputs = new Map([['messages.ts', typescriptOutput(catalog)]]);
  for (const locale of locales) {
    outputs.set(`arb/app_${locale.arb}.arb`, arbOutput(locale, catalog[locale.source]));
  }

  if (args.includes('--check')) {
    const stale = [];
    for (const [relativePath, expected] of outputs) {
      let actual;
      try {
        actual = readFileSync(path.join(outputDir, ...relativePath.split('/')), 'utf8');
      } catch {
        stale.push(relativePath);
        continue;
      }
      if (actual !== expected) stale.push(relativePath);
    }
    if (stale.length > 0) {
      throw new Error(`generated files are missing or stale: ${stale.join(', ')}; run node scripts/generate-i18n.mjs`);
    }
    console.log('translation catalogs are valid and generated files are up to date');
  } else {
    for (const relativePath of outputs.keys()) {
      mkdirSync(path.dirname(path.join(outputDir, ...relativePath.split('/'))), { recursive: true });
    }
    for (const [relativePath, contents] of outputs) {
      writeFileSync(path.join(outputDir, ...relativePath.split('/')), contents);
    }
    console.log(`generated ${outputs.size} translation files`);
  }
} catch (error) {
  console.error(`i18n generation: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
}
