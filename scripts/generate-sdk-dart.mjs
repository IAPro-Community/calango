#!/usr/bin/env node

// Generates packages/sdk-dart/lib/src/generated from api/openapi.yaml.
// The generator supports only the OpenAPI subset the Calango contract uses and
// fails on anything else, so an unsupported construct never yields a silently
// wrong client. Same input, same output: everything follows document order.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const specPath = path.join(root, 'api/openapi.yaml');
const outputDir = path.join(root, 'packages/sdk-dart/lib/src/generated');
const checkOnly = process.argv.includes('--check');

const header = [
  '// Generated by scripts/generate-sdk-dart.mjs from api/openapi.yaml. Do not edit.',
  '// dart format off',
  '// ignore_for_file: unintended_html_in_doc_comment',
];

const httpMethods = ['get', 'put', 'post', 'patch', 'delete'];

const dartReserved = new Set(
  (
    'abstract as assert async await base break case catch class const continue covariant default deferred do ' +
    'dynamic else enum export extends extension external factory false final finally for Function get hide if ' +
    'implements import in interface is late library mixin new null of on operator part required rethrow return ' +
    'sealed set show static super switch sync this throw true try type typedef var void when while with yield'
  ).split(' '),
);

// dart:core names a generated class must not shadow.
const dartCoreTypes = new Set(
  (
    'BigInt Comparable DateTime Deprecated Duration Enum Error Exception Expando Function Future Invocation ' +
    'Iterable Iterator List Map Match Never Null Object Pattern Record RegExp Runes Set Sink StackTrace Stream ' +
    'String StringBuffer Symbol Type Uri bool double int num'
  ).split(' '),
);

// Enum members must not clash with the members every Dart enum has.
const enumMemberReserved = new Set(['values', 'index', 'name', 'value', 'hashCode', 'runtimeType', 'toString']);

class GeneratorError extends Error {}

function unsupported(where, message) {
  throw new GeneratorError(`${where}: ${message}`);
}

function isRecord(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function words(text) {
  return text.split(/[^A-Za-z0-9]+/).filter(Boolean);
}

function pascal(text) {
  return words(text)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join('');
}

function camel(text) {
  const value = pascal(text);
  return value[0].toLowerCase() + value.slice(1);
}

function identifier(text, where) {
  const name = camel(text);
  if (!/^[a-z][A-Za-z0-9]*$/.test(name) || dartReserved.has(name)) {
    unsupported(where, `name ${JSON.stringify(text)} does not map to a valid Dart identifier`);
  }
  return name;
}

// enumMember maps an OpenAPI enum value to a Dart identifier, escaping reserved words.
function enumMember(value) {
  const name = camel(value);
  if (!dartReserved.has(name) && !enumMemberReserved.has(name)) return name;
  return `${name}Value`;
}

function className(schemaName) {
  const name = pascal(schemaName);
  if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) unsupported(schemaName, 'schema name is not a valid Dart class name');
  return dartCoreTypes.has(name) ? `${name}Body` : name;
}

function dartString(value) {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;
}

function docLines(indent, ...texts) {
  const paragraphs = texts
    .filter((text) => typeof text === 'string' && text.trim().length > 0)
    .map((text) => text.trim().replace(/\s+/g, ' '));
  const lines = [];
  paragraphs.forEach((paragraph, index) => {
    if (index > 0) lines.push(`${indent}///`);
    lines.push(`${indent}/// ${paragraph}`);
  });
  return lines;
}

let doc;

function resolvePointer(ref, where) {
  if (typeof ref !== 'string' || !ref.startsWith('#/'))
    unsupported(where, `only local references are supported (${ref})`);
  let node = doc;
  for (const part of ref.slice(2).split('/')) {
    const key = part.replace(/~1/g, '/').replace(/~0/g, '~');
    if (!isRecord(node) || !Object.hasOwn(node, key)) unsupported(where, `unresolved reference ${ref}`);
    node = node[key];
  }
  return node;
}

function deref(node, where) {
  let current = node;
  const seen = new Set();
  while (isRecord(current) && current.$ref !== undefined) {
    if (seen.has(current.$ref)) unsupported(where, `circular reference ${current.$ref}`);
    seen.add(current.$ref);
    current = resolvePointer(current.$ref, where);
  }
  return current;
}

const unsupportedKeywords = ['oneOf', 'anyOf', 'not', 'discriminator', 'patternProperties', 'prefixItems', 'const'];

function baseType(schema, where) {
  for (const keyword of unsupportedKeywords) {
    if (schema[keyword] !== undefined) unsupported(where, `${keyword} is not supported`);
  }
  let type = schema.type;
  let nullable = false;
  if (Array.isArray(type)) {
    const rest = type.filter((entry) => entry !== 'null');
    if (rest.length !== 1 || type.length - rest.length > 1)
      unsupported(where, 'only [type, "null"] unions are supported');
    nullable = rest.length !== type.length;
    type = rest[0];
  }
  if (type === undefined && schema.properties !== undefined) type = 'object';
  if (type === undefined && schema.allOf !== undefined) type = 'object';
  return { type, nullable };
}

// ---------------------------------------------------------------- type model

const classes = new Map(); // Dart class name -> class definition
const enumCandidates = []; // inline enums, named once every owner is known
const namedEnums = new Map(); // Dart enum name -> enum definition (component enums)
const schemaTypes = new Map(); // component schema name -> type ref

function enumValues(schema, where) {
  if (schema.type !== 'string' || !Array.isArray(schema.enum) || schema.enum.length === 0) {
    unsupported(where, 'only non-empty string enums are supported');
  }
  const members = schema.enum.map((value) => {
    if (typeof value !== 'string') unsupported(where, 'enum values must be strings');
    return { value, member: enumMember(value) };
  });
  if (new Set(members.map((entry) => entry.member)).size !== members.length) {
    unsupported(where, 'enum values collide after conversion to Dart names');
  }
  return members;
}

// owner: { full, base } names used to name inline types; prop: property name.
function typeOf(schemaNode, owner, prop, where) {
  if (isRecord(schemaNode) && schemaNode.$ref !== undefined) {
    const ref = schemaNode.$ref;
    const match = /^#\/components\/schemas\/([^/]+)$/.exec(ref);
    if (!match) unsupported(where, `schema references must point to components/schemas (${ref})`);
    const target = schemaType(match[1]);
    return { ...target, nullable: false };
  }
  if (!isRecord(schemaNode)) unsupported(where, 'schema must be an object');
  const { type, nullable } = baseType(schemaNode, where);
  if (schemaNode.enum !== undefined) {
    const values = enumValues({ ...schemaNode, type }, where);
    const candidate = { owner, prop, values, where, name: undefined, description: schemaNode.description };
    enumCandidates.push(candidate);
    return { kind: 'enum', candidate, nullable };
  }
  switch (type) {
    case 'string':
      return { kind: schemaNode.format === 'date-time' ? 'dateTime' : 'string', nullable };
    case 'integer':
      return { kind: 'int', nullable };
    case 'number':
      return { kind: 'double', nullable };
    case 'boolean':
      return { kind: 'bool', nullable };
    case 'array':
      if (schemaNode.items === undefined) unsupported(where, 'arrays need items');
      return { kind: 'list', item: typeOf(schemaNode.items, owner, prop, `${where}.items`), nullable };
    case 'object': {
      if (schemaNode.properties === undefined && schemaNode.allOf === undefined) {
        if (schemaNode.additionalProperties !== undefined && schemaNode.additionalProperties !== true) {
          unsupported(where, 'typed additionalProperties are not supported');
        }
        return { kind: 'map', nullable };
      }
      const name = `${owner.full}${pascal(prop)}`;
      // The same inline object reached again through allOf reuses its class.
      if (classes.get(name)?.schema !== schemaNode) defineClass(name, schemaNode, where);
      return { kind: 'model', name, nullable };
    }
    default:
      return unsupported(where, `unsupported schema type ${JSON.stringify(type)}`);
  }
}

function schemaType(schemaName) {
  if (schemaTypes.has(schemaName)) return schemaTypes.get(schemaName);
  const schemas = doc.components?.schemas ?? {};
  if (!Object.hasOwn(schemas, schemaName)) unsupported(schemaName, 'unknown schema');
  const schema = schemas[schemaName];
  const where = `components.schemas.${schemaName}`;
  const name = className(schemaName);
  if (schema.$ref !== undefined) unsupported(where, 'schema aliases are not supported');
  const { type } = baseType(schema, where);
  let result;
  if (schema.enum !== undefined) {
    const values = enumValues(schema, where);
    namedEnums.set(name, { name, values, description: schema.description });
    result = { kind: 'enum', candidate: { name }, nullable: false };
    schemaTypes.set(schemaName, result);
  } else if (type === 'object') {
    result = { kind: 'model', name, nullable: false };
    schemaTypes.set(schemaName, result);
    defineClass(name, schema, where);
  } else {
    result = typeOf(schema, { full: name, base: name }, '', where);
    schemaTypes.set(schemaName, result);
  }
  return result;
}

// Flattens allOf into its object parts. A part reached through a $ref keeps the referenced
// schema as owner, so RunDetail reuses RunStatus instead of generating RunDetailStatus.
function objectParts(schema, owner, where) {
  if (schema.allOf === undefined) return [{ schema, owner }];
  if (schema.properties !== undefined) unsupported(where, 'allOf together with properties is not supported');
  return schema.allOf.flatMap((part, index) => {
    const partWhere = `${where}.allOf[${index}]`;
    const resolved = deref(part, partWhere);
    if (baseType(resolved, partWhere).type !== 'object') unsupported(partWhere, 'allOf parts must be objects');
    const match = isRecord(part) && /^#\/components\/schemas\/([^/]+)$/.exec(part.$ref ?? '');
    return objectParts(resolved, match ? ownerFor(className(match[1])) : owner, partWhere);
  });
}

function ownerFor(name) {
  return { full: name, base: name.replace(/(Input|Patch)$/, '') };
}

function defineClass(name, schema, where) {
  if (classes.has(name)) unsupported(where, `class name ${name} is generated twice`);
  const placeholder = { name, fields: [], description: schema.description, where, schema };
  classes.set(name, placeholder);
  const required = new Set();
  const properties = [];
  for (const { schema: part, owner } of objectParts(schema, ownerFor(name), where)) {
    for (const key of part.required ?? []) required.add(key);
    for (const [key, value] of Object.entries(part.properties ?? {})) {
      const existing = properties.find((entry) => entry.key === key);
      if (existing) {
        if (JSON.stringify(existing.schema) !== JSON.stringify(value)) unsupported(where, `allOf redefines ${key}`);
        continue;
      }
      properties.push({ key, schema: value, owner });
    }
  }
  for (const key of required) {
    if (!properties.some((entry) => entry.key === key)) unsupported(where, `required property ${key} is not defined`);
  }
  for (const { key, schema: propertySchema, owner } of properties) {
    const fieldWhere = `${where}.properties.${key}`;
    const type = typeOf(propertySchema, owner, key, fieldWhere);
    const isRequired = required.has(key);
    const resolved = deref(propertySchema, fieldWhere);
    placeholder.fields.push({
      key,
      name: dartReserved.has(camel(key)) ? `${camel(key)}Value` : camel(key),
      type,
      required: isRequired,
      nullable: type.nullable || !isRequired,
      description: propertySchema.description,
      defaultValue: resolved.default,
      readOnly: propertySchema.readOnly === true,
      writeOnly: propertySchema.writeOnly === true,
    });
  }
  if (new Set(placeholder.fields.map((field) => field.name)).size !== placeholder.fields.length) {
    unsupported(where, 'property names collide after conversion to Dart names');
  }
}

// ---------------------------------------------------------------- operations

function successResponses(operation, where) {
  const entries = Object.entries(operation.responses ?? {});
  if (entries.length === 0) unsupported(where, 'operation has no responses');
  return entries.filter(([code]) => /^2\d\d$/.test(code)).map(([code, response]) => [code, deref(response, where)]);
}

function isWebSocket(operation) {
  const codes = Object.keys(operation.responses ?? {});
  return codes.includes('101') && !codes.some((code) => /^2\d\d$/.test(code));
}

function responseShape(operation, opName, where) {
  const shapes = successResponses(operation, where).map(([code, response]) => {
    const content = response.content;
    if (content === undefined) return { kind: 'void' };
    const types = Object.keys(content);
    if (types.length === 1 && types[0] === 'application/json') {
      const schema = content['application/json'].schema;
      if (schema === undefined) unsupported(`${where}.${code}`, 'JSON response needs a schema');
      return {
        kind: 'json',
        type: typeOf(schema, { full: `${opName}Response`, base: opName }, '', `${where}.responses.${code}`),
      };
    }
    if (types.includes('application/json')) unsupported(where, 'mixing JSON with other response types');
    for (const type of types) {
      if (deref(content[type].schema ?? {}, where).type !== 'string') unsupported(where, `${type} must be a string`);
    }
    return { kind: 'text' };
  });
  if (shapes.length === 0) unsupported(where, 'operation has no 2xx response');
  const first = JSON.stringify(shapes[0], (key, value) => (key === 'candidate' ? undefined : value));
  for (const shape of shapes.slice(1)) {
    if (JSON.stringify(shape, (key, value) => (key === 'candidate' ? undefined : value)) !== first) {
      unsupported(where, '2xx responses must share one shape');
    }
  }
  return shapes[0];
}

function collectParameters(pathItem, operation, where) {
  const merged = [];
  for (const raw of [...(pathItem.parameters ?? []), ...(operation.parameters ?? [])]) {
    const parameter = deref(raw, where);
    const index = merged.findIndex((entry) => entry.name === parameter.name && entry.in === parameter.in);
    if (index >= 0) merged[index] = parameter;
    else merged.push(parameter);
  }
  for (const parameter of merged) {
    if (!['path', 'query', 'header'].includes(parameter.in)) unsupported(where, `${parameter.in} parameters`);
    if (parameter.schema === undefined || parameter.content !== undefined)
      unsupported(where, 'parameters need a schema');
  }
  return merged;
}

const operations = [];
const skipped = [];
const enums = new Map();

function build() {
  doc = yaml.load(readFileSync(specPath, 'utf8'), { schema: yaml.CORE_SCHEMA });
  for (const name of Object.keys(doc.components?.schemas ?? {})) schemaType(name);
  buildOperations();
  nameEnums();
}

function buildOperations() {
  for (const [route, pathItem] of Object.entries(doc.paths ?? {})) {
    for (const method of Object.keys(pathItem)) {
      if (method === 'parameters' || method === 'summary' || method === 'description') continue;
      if (!httpMethods.includes(method)) unsupported(`${route}`, `unsupported method ${method}`);
    }
    for (const method of Object.keys(pathItem).filter((key) => httpMethods.includes(key))) {
      const operation = pathItem[method];
      const where = `${method.toUpperCase()} ${route}`;
      if (typeof operation.operationId !== 'string') unsupported(where, 'operationId is required');
      const methodName = identifier(operation.operationId, where);
      if (isWebSocket(operation)) {
        skipped.push({ methodName, method, route });
        continue;
      }
      const opName = pascal(operation.operationId);
      const owner = { full: opName, base: opName, operation: true };
      const parameters = collectParameters(pathItem, operation, where).map((parameter) => {
        const type = typeOf(parameter.schema, owner, parameter.name, `${where} parameter ${parameter.name}`);
        if (parameter.in === 'path' && (type.kind !== 'string' || parameter.required !== true)) {
          unsupported(where, `path parameter ${parameter.name} must be a required string`);
        }
        if (!['string', 'int', 'bool', 'enum', 'dateTime', 'double'].includes(type.kind)) {
          unsupported(where, `parameter ${parameter.name} must be a scalar`);
        }
        return {
          key: parameter.name,
          location: parameter.in,
          name: identifier(parameter.name, where),
          type,
          required: parameter.required === true,
          description: parameter.description,
          param: true,
        };
      });
      const templateNames = [...route.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
      const pathNames = parameters.filter((entry) => entry.location === 'path').map((entry) => entry.key);
      if (templateNames.length !== pathNames.length || templateNames.some((name) => !pathNames.includes(name))) {
        unsupported(where, 'path template and path parameters differ');
      }

      let body;
      if (operation.requestBody !== undefined) {
        const requestBody = deref(operation.requestBody, where);
        const types = Object.keys(requestBody.content ?? {});
        if (types.length !== 1 || types[0] !== 'application/json')
          unsupported(where, 'request bodies must be JSON only');
        const schema = requestBody.content['application/json'].schema;
        if (schema === undefined) unsupported(where, 'request body needs a schema');
        const required = requestBody.required === true;
        if (schema.$ref !== undefined) {
          const type = typeOf(schema, owner, 'body', `${where} requestBody`);
          if (type.kind !== 'model') unsupported(where, 'referenced request bodies must be objects');
          body = { kind: 'model', type, required, description: requestBody.description };
        } else {
          const resolved = deref(schema, where);
          if (baseType(resolved, where).type !== 'object' || resolved.allOf !== undefined) {
            unsupported(where, 'inline request bodies must be plain objects');
          }
          if (resolved.additionalProperties !== undefined && resolved.additionalProperties !== false) {
            unsupported(where, 'inline request bodies cannot have additionalProperties');
          }
          const requiredKeys = new Set(resolved.required ?? []);
          const fields = Object.entries(resolved.properties ?? {}).map(([key, propertySchema]) => {
            const fieldWhere = `${where} requestBody.${key}`;
            const type = typeOf(propertySchema, owner, key, fieldWhere);
            return {
              key,
              name: dartReserved.has(camel(key)) ? `${camel(key)}Value` : camel(key),
              type,
              required: requiredKeys.has(key),
              nullable: type.nullable || !requiredKeys.has(key),
              description: propertySchema.description,
              defaultValue: deref(propertySchema, fieldWhere).default,
            };
          });
          body = { kind: 'fields', fields, required };
        }
      }

      const names = [
        ...parameters.map((entry) => entry.name),
        ...(body?.kind === 'fields' ? body.fields.map((field) => field.name) : []),
        ...(body?.kind === 'model' ? ['body'] : []),
      ];
      if (new Set(names).size !== names.length) unsupported(where, 'parameter names collide after conversion');

      const security = operation.security ?? doc.security ?? [];
      operations.push({
        methodName,
        method: method.toUpperCase(),
        route,
        summary: operation.summary,
        description: operation.description,
        parameters,
        body,
        response: responseShape(operation, opName, where),
        authenticated: !(Array.isArray(security) && security.length === 0),
      });
    }
  }

  if (new Set(operations.map((operation) => operation.methodName)).size !== operations.length) {
    unsupported('paths', 'operationIds collide after conversion');
  }
}

// ---------------------------------------------------------------- enum names

const sameValues = (a, b) => a.length === b.length && a.every((entry, index) => entry.value === b[index].value);

function nameEnums() {
  for (const [name, definition] of namedEnums) enums.set(name, definition);
  const classOwned = enumCandidates.filter((candidate) => !candidate.owner.operation);
  const operationOwned = enumCandidates.filter((candidate) => candidate.owner.operation);

  // Inline enums of a model share one name per base owner and property (RoutineInput.run_on and
  // Routine.run_on become RoutineRunOn) when every occurrence has the same values; otherwise each
  // keeps its full owner name.
  const byBase = new Map();
  for (const candidate of classOwned) {
    const key = `${candidate.owner.base}${pascal(candidate.prop)}`;
    if (!byBase.has(key)) byBase.set(key, []);
    byBase.get(key).push(candidate);
  }
  for (const [baseName, group] of byBase) {
    const shared = group.every((candidate) => sameValues(candidate.values, group[0].values));
    for (const candidate of group) {
      candidate.name = shared ? baseName : `${candidate.owner.full}${pascal(candidate.prop)}`;
    }
  }

  // Operation parameters and inline bodies reuse a model enum when exactly one model enum has the
  // same property name and the same values (listApprovals status is ApprovalStatus).
  for (const candidate of operationOwned) {
    const matches = new Set(
      classOwned
        .filter((other) => other.prop === candidate.prop && sameValues(other.values, candidate.values))
        .map((other) => other.name),
    );
    candidate.name = matches.size === 1 ? [...matches][0] : `${candidate.owner.full}${pascal(candidate.prop)}`;
  }

  for (const candidate of enumCandidates) {
    const existing = enums.get(candidate.name);
    if (existing) {
      if (!sameValues(existing.values, candidate.values))
        unsupported(candidate.where, `enum ${candidate.name} conflicts`);
      continue;
    }
    if (classes.has(candidate.name)) unsupported(candidate.where, `enum ${candidate.name} clashes with a class`);
    enums.set(candidate.name, { name: candidate.name, values: candidate.values, description: candidate.description });
  }
}

// ---------------------------------------------------------------- Dart code

function typeName(type) {
  switch (type.kind) {
    case 'string':
      return 'String';
    case 'int':
      return 'int';
    case 'double':
      return 'double';
    case 'bool':
      return 'bool';
    case 'dateTime':
      return 'DateTime';
    case 'map':
      return 'Map<String, Object?>';
    case 'list':
      return `List<${typeName(type.item)}>`;
    case 'model':
      return type.name;
    case 'enum':
      return type.candidate.name;
    default:
      throw new GeneratorError(`unknown type ${type.kind}`);
  }
}

// Expression converting a non-null JSON value `expr` into the Dart type.
function decode(type, expr) {
  switch (type.kind) {
    case 'string':
    case 'int':
    case 'bool':
      return `${expr} as ${typeName(type)}`;
    case 'double':
      return `(${expr} as num).toDouble()`;
    case 'dateTime':
      return `DateTime.parse(${expr} as String)`;
    case 'map':
      return `${expr} as Map<String, Object?>`;
    case 'model':
      return `${type.name}.fromJson(${expr} as Map<String, Object?>)`;
    case 'enum':
      return `${type.candidate.name}.fromJson(${expr} as String)`;
    case 'list':
      return `(${expr} as List<Object?>).map((e) => ${decode(type.item, 'e')}).toList()`;
    default:
      throw new GeneratorError(`unknown type ${type.kind}`);
  }
}

function decodeNullable(type, expr) {
  if (['string', 'int', 'bool', 'map'].includes(type.kind)) return `${expr} as ${typeName(type)}?`;
  return `${expr} == null ? null : ${decode(type, expr)}`;
}

// Expression converting a Dart value into JSON; `access` is '.' or '?.' for nullable values.
function encode(type, expr, access = '.') {
  switch (type.kind) {
    case 'string':
    case 'int':
    case 'double':
    case 'bool':
    case 'map':
      return expr;
    case 'dateTime':
      return `${expr}${access}toUtc().toIso8601String()`;
    case 'model':
    case 'enum':
      return `${expr}${access}toJson()`;
    case 'list':
      if (['string', 'int', 'double', 'bool', 'map'].includes(type.item.kind)) return expr;
      return `${expr}${access}map((e) => ${encode(type.item, 'e')}).toList()`;
    default:
      throw new GeneratorError(`unknown type ${type.kind}`);
  }
}

// Map entry for a field; optional fields are omitted when null.
function jsonEntry(field, expr) {
  if (!field.nullable) return `${dartString(field.key)}: ${encode(field.type, expr)}`;
  if (field.required) return `${dartString(field.key)}: ${encode(field.type, expr, '?.')}`;
  return `${dartString(field.key)}: ?${encode(field.type, expr, '?.')}`;
}

function fieldDocs(field, indent) {
  const notes = [];
  if (field.defaultValue !== undefined) notes.push(`Server default: \`${JSON.stringify(field.defaultValue)}\`.`);
  if (field.readOnly) notes.push('Read-only: set by the server in responses.');
  if (field.writeOnly) notes.push('Write-only: never returned by the server.');
  return docLines(indent, field.description, notes.join(' '));
}

function emitEnum(definition) {
  const lines = [...docLines('', definition.description), `enum ${definition.name} {`];
  definition.values.forEach((entry, index) => {
    const last = index === definition.values.length - 1;
    lines.push(`  ${entry.member}(${dartString(entry.value)})${last ? ';' : ','}`);
  });
  lines.push(
    '',
    `  const ${definition.name}(this.value);`,
    '',
    '  /// Wire value in the API.',
    '  final String value;',
    '',
    `  static ${definition.name} fromJson(String value) {`,
    `    for (final candidate in ${definition.name}.values) {`,
    '      if (candidate.value == value) return candidate;',
    '    }',
    `    throw FormatException('Unknown ${definition.name} value', value);`,
    '  }',
    '',
    '  String toJson() => value;',
    '}',
  );
  return lines.join('\n');
}

function emitClass(definition) {
  const lines = [...docLines('', definition.description), `final class ${definition.name} {`];
  if (definition.fields.length === 0) {
    lines.push(`  const ${definition.name}();`);
  } else {
    lines.push(`  const ${definition.name}({`);
    for (const field of definition.fields) {
      lines.push(`    ${field.required ? 'required ' : ''}this.${field.name},`);
    }
    lines.push('  });');
  }
  lines.push('');
  lines.push(`  factory ${definition.name}.fromJson(Map<String, Object?> json) {`);
  if (definition.fields.length === 0) {
    lines.push(`    return const ${definition.name}();`);
  } else {
    lines.push(`    return ${definition.name}(`);
    for (const field of definition.fields) {
      const expr = `json[${dartString(field.key)}]`;
      lines.push(
        `      ${field.name}: ${field.nullable ? decodeNullable(field.type, expr) : decode(field.type, expr)},`,
      );
    }
    lines.push('    );');
  }
  lines.push('  }');
  for (const field of definition.fields) {
    lines.push(
      '',
      ...fieldDocs(field, '  '),
      `  final ${typeName(field.type)}${field.nullable ? '?' : ''} ${field.name};`,
    );
  }
  lines.push('');
  lines.push('  Map<String, Object?> toJson() {');
  lines.push('    return <String, Object?>{');
  for (const field of definition.fields) lines.push(`      ${jsonEntry(field, field.name)},`);
  lines.push('    };');
  lines.push('  }');
  lines.push('}');
  return lines.join('\n');
}

function modelsOutput() {
  const parts = [header.join('\n')];
  for (const definition of classes.values()) parts.push(emitClass(definition));
  for (const name of [...enums.keys()].sort()) parts.push(emitEnum(enums.get(name)));
  return `${parts.join('\n\n')}\n`;
}

function scalarToString(type, expr, access = '.') {
  switch (type.kind) {
    case 'string':
      return expr;
    case 'enum':
      return `${expr}${access}value`;
    case 'dateTime':
      return `${expr}${access}toUtc().toIso8601String()`;
    default:
      return `${expr}${access}toString()`;
  }
}

function emitOperation(operation) {
  const positional = [];
  const named = [];
  const pathParams = operation.parameters.filter((entry) => entry.location === 'path');
  for (const parameter of pathParams) positional.push(`String ${parameter.name}`);
  if (operation.body?.kind === 'model') {
    if (operation.body.required) positional.push(`${operation.body.type.name} body`);
    else named.push(`${operation.body.type.name}? body`);
  }
  const namedFields = [
    ...(operation.body?.kind === 'fields' ? operation.body.fields : []),
    ...operation.parameters.filter((entry) => entry.location !== 'path'),
  ];
  for (const field of namedFields) {
    const required = field.param ? field.required : field.required && !field.type.nullable;
    named.push(`${required ? 'required ' : ''}${typeName(field.type)}${required ? '' : '?'} ${field.name}`);
  }
  const signature = [...positional];
  if (named.length > 0) signature.push(`{${named.join(', ')}}`);

  const returnType =
    operation.response.kind === 'void'
      ? 'void'
      : operation.response.kind === 'text'
        ? 'String'
        : typeName(operation.response.type);

  const routeExpr = operation.route.replace(/\{([^}]+)\}/g, (_, name) => {
    const parameter = pathParams.find((entry) => entry.key === name);
    return `\${Uri.encodeComponent(${parameter.name})}`;
  });

  const paramDocs = [];
  for (const field of namedFields.filter((entry) => entry.description)) {
    paramDocs.push(`[${field.name}]: ${field.description.trim().replace(/\s+/g, ' ')}`);
  }

  const lines = [...docLines('  ', operation.summary, operation.description, ...paramDocs)];
  lines.push(`  Future<${returnType}> ${operation.methodName}(${signature.join(', ')}) async {`);
  const call = operation.response.kind === 'text' ? 'sendText' : 'sendJson';
  const assign = operation.response.kind === 'void' ? 'await' : 'final response = await';
  lines.push(`    ${assign} _transport.${call}(`);
  lines.push(`      ${dartString(operation.method)},`);
  lines.push(`      '${routeExpr.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`);
  const query = operation.parameters.filter((entry) => entry.location === 'query');
  if (query.length > 0) {
    lines.push('      query: <String, String?>{');
    for (const parameter of query) {
      const access = parameter.required ? '.' : '?.';
      lines.push(`        ${dartString(parameter.key)}: ${scalarToString(parameter.type, parameter.name, access)},`);
    }
    lines.push('      },');
  }
  const headers = operation.parameters.filter((entry) => entry.location === 'header');
  if (headers.length > 0) {
    lines.push('      headers: <String, String>{');
    for (const parameter of headers) {
      const prefix = parameter.required ? '' : '?';
      const access = parameter.required ? '.' : '?.';
      lines.push(
        `        ${dartString(parameter.key)}: ${prefix}${scalarToString(parameter.type, parameter.name, access)},`,
      );
    }
    lines.push('      },');
  }
  if (operation.body?.kind === 'model') {
    lines.push(`      body: body${operation.body.required ? '' : '?'}.toJson(),`);
  } else if (operation.body?.kind === 'fields') {
    lines.push('      body: <String, Object?>{');
    for (const field of operation.body.fields) lines.push(`        ${jsonEntry(field, field.name)},`);
    lines.push('      },');
  }
  if (!operation.authenticated) lines.push('      authenticated: false,');
  lines.push('    );');
  if (operation.response.kind === 'text') {
    lines.push('    return response;');
  } else if (operation.response.kind === 'json') {
    lines.push(`    return ${decode(operation.response.type, 'response')};`);
  }
  lines.push('  }');
  return lines.join('\n');
}

function clientOutput() {
  const lines = [header.join('\n'), '', "import '../transport.dart';", "import 'models.dart';", ''];
  lines.push('/// Client for every REST operation of the Calango node API.');
  if (skipped.length > 0) {
    lines.push('///');
    lines.push('/// Not generated (WebSocket upgrades, outside this REST client):');
    for (const entry of skipped)
      lines.push(`/// - \`${entry.methodName}\` (${entry.method.toUpperCase()} ${entry.route}).`);
  }
  lines.push('final class CalangoClient {');
  lines.push('  const CalangoClient(this._transport);');
  lines.push('');
  lines.push('  final CalangoTransport _transport;');
  for (const operation of operations) lines.push('', emitOperation(operation));
  lines.push('}', '');
  return lines.join('\n');
}

try {
  build();
  const outputs = new Map([
    ['models.dart', modelsOutput()],
    ['client.dart', clientOutput()],
  ]);
  if (checkOnly) {
    const stale = [];
    for (const [file, expected] of outputs) {
      let actual;
      try {
        actual = readFileSync(path.join(outputDir, file), 'utf8');
      } catch {
        stale.push(file);
        continue;
      }
      if (actual !== expected) stale.push(file);
    }
    if (stale.length > 0) {
      console.error(
        `dart sdk generation: generated files are missing or stale: ${stale.join(', ')}; run npm run sdk:generate:dart`,
      );
      process.exitCode = 1;
    } else {
      console.log('dart sdk is up to date with api/openapi.yaml');
    }
  } else {
    mkdirSync(outputDir, { recursive: true });
    for (const [file, contents] of outputs) writeFileSync(path.join(outputDir, file), contents);
    console.log(
      `generated ${outputs.size} dart sdk files (${classes.size} classes, ${enums.size} enums, ${operations.length} operations)`,
    );
  }
} catch (error) {
  if (error instanceof Error && error.stack) console.error(error.stack);
  console.error(`dart sdk generation: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
}
